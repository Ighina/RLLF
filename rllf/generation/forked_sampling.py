"""Sampling a `ForkedTree` (see `rllf/data/forked_tree.py`) from a
step-native base model.

    T0:  s1  s2  s3  s4  <final>
    T1:  s1  s2  s3' s4' <final>        fork at k=2 from T0
    T2:  s1' s2'' s3''   <final>        fork at k=0 from T0 (fresh from the start)
    T3:  s1  s2  s3' s4'' <final>       fork at k=3 from T1

Every trajectory is a complete solution (experiment 1's unit); every fork
point is a pair of siblings behind an identical prefix (experiment 2's
unit); every step is generated by the model that will be decoded, step by
step at its own `<step>` boundary, so the classifier trained on it is scored
on the distribution it will meet -- `experiments_v1.md` §10.2's transfer gap
is the reason for all three.

The base model only needs `generate_step_candidates` (one sampled step for
a given history, `<final>`/`\\boxed` preserved) -- `StepNativeHFBaseModel`
for the real thing, any scripted double for tests.
"""

from __future__ import annotations

import random
import time
from dataclasses import dataclass
from typing import Any, List, Optional, Tuple

from ..data.forked_tree import ForkedTrajectory, ForkedTree
from ..protocol import contains_final_answer
from .guided_decoder import MAX_STEPS_SAFETY_CEILING


@dataclass
class ForkConfig:
    #: Total trajectories per problem, roots + forks.
    n_trajectories: int = 4
    #: How many are sampled from scratch before forking starts (>= 1).
    n_independent: int = 1
    #: Step budget per trajectory; None = the safety ceiling only
    #: (`experiments_v1.md` §9: a tight cap guarantees empty final answers).
    max_steps: Optional[int] = None
    max_new_tokens: int = 256
    temperature: float = 0.8
    top_p: float = 0.95
    seed: int = 0


def _sample_one_step(question: str, history: List[str], base_model: Any, config: ForkConfig, rng: random.Random) -> str:
    candidates = base_model.generate_step_candidates(
        question, history, num_candidates=1,
        temperature=config.temperature, top_p=config.top_p,
        max_new_tokens=config.max_new_tokens, seed=rng.randrange(2**31),
    )
    return candidates[0].strip() if candidates else ""


def continue_trajectory(
    question: str, prefix: List[str], base_model: Any, config: ForkConfig, rng: random.Random,
) -> Tuple[List[str], str, str]:
    """Extend `prefix` one sampled step at a time until the model emits a
    final segment, an empty step, or the step budget runs out.

    Returns `(steps, final_answer, stop_reason)` with `stop_reason` in
    `{"final", "empty", "max_steps"}`; `final_answer` is the raw final segment
    (never a reasoning step) or "" when none was produced.
    """
    steps = list(prefix)
    ceiling = config.max_steps if config.max_steps is not None else MAX_STEPS_SAFETY_CEILING
    while len(steps) < ceiling:
        step = _sample_one_step(question, steps, base_model, config, rng)
        if not step:
            return steps, "", "empty"
        if contains_final_answer(step):
            return steps, step, "final"
        steps.append(step)
    return steps, "", "max_steps"


def sample_forked_tree(
    question: str,
    reference: Any,
    base_model: Any,
    outcome_checker: Any = None,
    config: Optional[ForkConfig] = None,
) -> ForkedTree:
    config = config or ForkConfig()
    rng = random.Random(config.seed)
    trajectories: List[ForkedTrajectory] = []
    started = time.perf_counter()

    for index in range(config.n_trajectories):
        t0 = time.perf_counter()
        parent: Optional[int] = None
        fork_index: Optional[int] = None
        prefix: List[str] = []
        if index >= config.n_independent:
            # Fork points: every (trajectory, step) so far. A step position,
            # not the final segment -- a sibling of the *answer* is not a
            # reasoning-step comparison. Uniform over positions, so longer
            # trajectories are forked more often (they have more decisions).
            points = [
                (ti, k) for ti, traj in enumerate(trajectories) for k in range(len(traj.steps))
            ]
            if points:
                parent, fork_index = rng.choice(points)
                prefix = trajectories[parent].steps[:fork_index]
        steps, final_answer, stop_reason = continue_trajectory(question, prefix, base_model, config, rng)
        correct: Optional[float] = None
        if outcome_checker is not None and reference is not None:
            correct = float(outcome_checker.check(question, final_answer, reference).reward)
        metadata = {"stop_reason": stop_reason, "seconds": time.perf_counter() - t0}
        if parent is not None and fork_index is not None:
            sibling = trajectories[parent].steps[fork_index]
            metadata["identical_sibling"] = (
                fork_index < len(steps) and steps[fork_index].strip() == sibling.strip()
            )
        trajectories.append(
            ForkedTrajectory(
                steps=steps, final_answer=final_answer, parent=parent,
                fork_index=fork_index, correct=correct, metadata=metadata,
            )
        )

    return ForkedTree(
        question=question,
        reference=None if reference is None else str(reference),
        trajectories=trajectories,
        metadata={
            "n_trajectories": config.n_trajectories, "n_independent": config.n_independent,
            "seed": config.seed, "seconds": time.perf_counter() - started,
        },
    )
